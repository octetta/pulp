#!/usr/bin/env python3
"""
build_drum_sources.py - Packs .ks drum scripts into C string sources in drums_sources.h
"""

import os
import glob
import re

SCRIPT_DIR = os.path.dirname(os.path.realpath(__file__))
PARTS_DIR = os.path.abspath(os.path.join(SCRIPT_DIR, ".."))
DRUMS_DIR = os.path.join(PARTS_DIR, "waves", "drums")
OUT_FILE = os.path.join(PARTS_DIR, "drums_sources.h")

def main():
    ks_files = sorted(glob.glob(os.path.join(DRUMS_DIR, "*.ks")),
                      key=lambda p: [int(c) if c.isdigit() else c for c in re.split(r'(\d+)', os.path.basename(p))])
    
    entries = []
    for filepath in ks_files:
        basename = os.path.splitext(os.path.basename(filepath))[0]
        m = re.match(r"^(\d+)_(.+)$", basename)
        if not m:
            continue
        slot = int(m.group(1))
        name = m.group(2)
        
        with open(filepath, "r", encoding="utf-8") as f:
            lines = f.readlines()
        
        c_lines = []
        for line in lines:
            # Strip trailing newline for escaping
            line_content = line.rstrip("\r\n")
            escaped = line_content.replace("\\", "\\\\").replace('"', '\\"')
            c_lines.append(f'        "{escaped}\\n"')
        
        code_str = "\n".join(c_lines)
        entries.append((slot, name, code_str))
    
    out_lines = [
        "// Generated by tools/build_drum_sources.py",
        "// Do not edit directly.",
        "",
        "#ifndef DRUMS_SOURCES_H",
        "#define DRUMS_SOURCES_H",
        "",
        "typedef struct {",
        "    int slot;",
        "    const char *name;",
        "    const char *ks_code;",
        "} drum_patch_source_t;",
        "",
        "static const drum_patch_source_t DRUM_PATCH_SOURCES[] = {"
    ]
    
    for slot, name, code in entries:
        out_lines.append(f"    {{\n        {slot}, \"{name}\",\n{code}\n    }},")
    
    out_lines.append("    { 0, 0, 0 }")
    out_lines.append("};")
    out_lines.append("")
    out_lines.append("#endif /* DRUMS_SOURCES_H */")
    out_lines.append("")
    
    with open(OUT_FILE, "w", encoding="utf-8") as f:
        f.write("\n".join(out_lines))
    
    print(f"Generated {OUT_FILE} with {len(entries)} drum patches.")

if __name__ == "__main__":
    main()
